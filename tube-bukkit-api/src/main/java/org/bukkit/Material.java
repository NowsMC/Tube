    private static final Map<String, Material> BY_KEY = new HashMap<>();

    static {
        for (Material material : values()) {
            BY_KEY.put(material.key, material);
        }
    }

    private final String key;
    private final boolean item;
    private final boolean block;

    Material(String key, boolean item, boolean block) {
        this.key = key;
        this.item = item;
        this.block = block;
    }

    public NamespacedKey getKey() {
        return NamespacedKey.minecraft(key);
    }

    public boolean isBlock() {
        return block;
    }

    public boolean isItem() {
        return item;
    }

    public boolean isAir() {
        return this == AIR || this == CAVE_AIR || this == VOID_AIR;
    }

    public boolean isSolid() {
        return block && !isAir() && this != WATER && this != LAVA && this != BUBBLE_COLUMN;
    }

    public int getMaxStackSize() {
        return 64;
    }

    public static Material getMaterial(String name) {
        return name == null ? null : valueOf0(name.toUpperCase(Locale.ROOT));
    }

    public static Material matchMaterial(String name) {
        if (name == null) {
            return null;
        }
        String normalized = name.toLowerCase(Locale.ROOT).replace(' ', '_');
        if (normalized.startsWith("minecraft:")) {
            normalized = normalized.substring("minecraft:".length());
        }
        return BY_KEY.get(normalized);
    }

    private static Material valueOf0(String name) {
        try {
            return valueOf(name);
        } catch (IllegalArgumentException e) {
            return null;
        }
    }
